#!/usr/bin/env python3
"""The Pacific Conflict overlay's object definition table, read from its bytes: the built-in
records overlay_init_template_pointer_tables (file 0x54) copies into DAT_0001b524[key], each a key
word and six handler longs (runtime addresses), named from the strict port's overlay method map
(godot/hellcats/data/overlay_methods.json), the registry, or the runtime's written routines.

Writes docs/OVERLAY_DEFINITION_TABLE.md; --check fails when the document is stale.

Usage: python3 tools/decomp/definition_table.py [--check]
"""
from __future__ import annotations

import json
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OVERLAY = ROOT / "godot" / "hellcats" / "data" / "scenery" / "Pacific Conflict"
METHODS = ROOT / "godot" / "hellcats" / "data" / "overlay_methods.json"
INVENTORY = ROOT / "docs" / "DECOMPILATION_INVENTORY.json"
DOC = ROOT / "docs" / "OVERLAY_DEFINITION_TABLE.md"
DELTA = 0x20                      # runtime address = file offset - 0x20

# The records, as overlay_init_template_pointer_tables copies them (runtime source, size, the slot
# offset for the fixed-slot ones; the keyed ones go to the slot their first word names).
KEYED = [(0x1A790 + 0x4A * k, 0x4A) for k in range(4)] + [(0x1AA5E + 0x1C * k, 0x1C) for k in range(5)]
FIXED = [(0x1A8B8, 0x1A, 0x14), (0x1A8D2, 0x1A, 0x18), (0x1A8EC, 0x1A, 0x1C), (0x1A906, 0x1A, 0x28),
         (0x1A920, 0x1A, 0x2C), (0x1A93A, 0x1A, 0x20), (0x1A954, 0x1A, 0x24), (0x1A96E, 0x1A, 0x44),
         (0x1A988, 0x20, 0x30), (0x1A9A8, 0x1A, 0x34), (0x1A9C2, 0x1A, 0x38), (0x1A9DC, 0x1A, 0x3C),
         (0x1A9F6, 0x1A, 0x40), (0x1AA10, 0x1A, 0x48), (0x1AA2A, 0x1A, 0x4C), (0x1AA44, 0x1A, 0x50),
         (0x1AAEA, 0x1A, 0x68), (0x1AB04, 0x1A, 0x6C), (0x1AB1E, 0x1A, 0x70), (0x1AB38, 0x1A, 0x74),
         (0x1AB52, 0x1A, 0x78)]
SLOTS = ["+2 tick", "+6 create", "+0xa destroy", "+0xe render", "+0x12 collision", "+0x16 notice"]
WRITTEN = {0x15134: "carrier_deck_contact (runtime-written)"}
RTS_ONLY = {0x12F70: "(an RTS)"}


def installed_factory(image: bytes, hook: int) -> int:
    """The factory a registration hook installs: the immediate of its MOVE.L #factory, 6(An) (the
    record's +6 rewritten), up to its RTS; 0 for a create handler that installs none."""
    import capstone
    md = capstone.Cs(capstone.CS_ARCH_M68K, capstone.CS_MODE_M68K_020)
    start = hook + DELTA
    for ins in md.disasm(image[start:start + 0x100], start):
        if ins.mnemonic == "rts":
            break
        operands = ins.op_str.replace(" ", "")
        if ins.mnemonic == "move.l" and operands.startswith("#$") and operands.endswith(")") and ",$6(a" in operands:
            return int(operands[2:operands.index(",")], 16)
    return 0


def records() -> list[dict]:
    image = OVERLAY.read_bytes()
    methods = {int(k, 16): v for k, v in json.loads(METHODS.read_text(encoding="utf-8")).items()}
    rows = json.loads(INVENTORY.read_text(encoding="utf-8"))
    rows = rows if isinstance(rows, list) else rows["functions"]
    registry = {int(r["original_address"], 16) - DELTA: r["semantic_name"] for r in rows if r["segment"] == "Pacific Conflict"}

    def name(address: int) -> str:
        if address == 0:
            return "-"
        found = methods.get(address) or registry.get(address) or WRITTEN.get(address) or RTS_ONLY.get(address)
        if found is None:
            raise SystemExit(f"handler 0x{address:x} has no name")
        return found

    out = []
    for source, size, slot in [(s, z, None) for s, z in KEYED] + FIXED:
        at = source + DELTA
        word = struct.unpack(">h", image[at:at + 2])[0]
        key = word if slot is None else slot // 4
        if slot is not None and word != key:
            raise SystemExit(f"fixed record 0x{source:x}: first word {word} is not its slot's key {key}")
        handlers = [struct.unpack(">I", image[at + 2 + 4 * i:at + 6 + 4 * i])[0] for i in range(6)]
        out.append({"key": key, "source": source, "size": size, "keyed": slot is None,
                    "handlers": [name(h) for h in handlers],
                    "factory": name(installed_factory(image, handlers[1])) if handlers[1] else "-"})
    return sorted(out, key=lambda r: r["key"])


def document() -> str:
    lines = [
        "# Overlay object definition table",
        "",
        "Generated by `tools/decomp/definition_table.py` from the *Pacific Conflict* overlay's bytes; do not",
        "edit by hand (`--check` in validation).",
        "",
        "`overlay_init_template_pointer_tables` (file 0x54, called by `init_mission_object_tables`) copies",
        "the built-in definition records onto the heap and stores them in `DAT_0001b524[key]`. Each record is",
        "a key word and six handler longs (runtime addresses, file offset - 0x20); an object's definition",
        "(controller +4) is its record. The aircraft records (0x4a bytes) continue with the flight data that",
        "docs/DECOMPILATION_SYMBOLS.md's aircraft type record lists. Every record's first word equals its",
        "key, including the fixed-slot ones, which are stored at their slot offset. Each slot's role is",
        "its dispatcher's (in the strict port, godot/strict_port/code/pacific_conflict.gd):",
        "",
        "- +2 tick (controller): every frame, `advance_frame_and_tick_controllers` and",
        "  `tick_flagged_object_controllers`;",
        "- +6 create (object, key, word): `instantiate_object_from_desc` through `_call_class_factory`;",
        "  it returns the controller;",
        "- +0xa destroy (controller): `_free_far_object`, before the controller is freed;",
        "- +0xe render (controller, phase): `transform_and_project_object`. Phase 1 runs before the object",
        "  is transformed: result bit 4 skips it, bit 1 keeps the controller's own attitude matrix and bit 2",
        "  asks for phase 2, which runs once the object's relative position is computed;",
        "- +0x12 collision (other object, object, contact record): the shape-collision path, when the",
        "  other object's byte +6 bit 6 is set (`carrier_deck_contact` is key 0x15's);",
        "- +0x16 notice: `dispatch_overlap_collisions`, for the objects on the overlap list.",
        "",
        "The create slot of many records holds a registration hook (`register_*`): the first object made",
        "with that key is kept as the template, the hook rewrites the record's +6 to the factory (its",
        "`MOVE.L #factory, 6(An)`, read from its bytes) and returns 0. Later objects go to that factory,",
        "listed in the last column (- where the create handler installs none).",
        "",
        "| Key | Source (runtime) | Size | " + " | ".join(SLOTS) + " | +6 after registration |",
        "|---|---|---|" + "---|" * (len(SLOTS) + 1),
    ]
    for r in records():
        source = f"0x{r['source']:x}" + ("" if r["keyed"] else " (fixed)")
        lines.append(f"| 0x{r['key']:x} | {source} | 0x{r['size']:x} | " + " | ".join(
            "-" if h == "-" else f"`{h}`" if " " not in h else h for h in r["handlers"] + [r["factory"]]) + " |")
    return "\n".join(lines) + "\n"


def main() -> int:
    text = document()
    if "--check" in sys.argv:
        if not DOC.exists() or DOC.read_text(encoding="utf-8") != text:
            print(f"FAIL {DOC.relative_to(ROOT)} is stale; rerun without --check")
            return 1
        print("PASS overlay definition table is up to date")
        return 0
    DOC.write_text(text, encoding="utf-8")
    print(f"wrote {DOC.relative_to(ROOT)}: {len(records())} records")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
